//! Per-user launchd configuration; installation never invokes the manager.

use std::path::Path;

use super::{CliFailure, CliResult, HostInstall, service_arguments};

const LABEL: &str = "com.plak.host";
#[cfg(any(target_os = "macos", test))]
const PLIST: &str = "com.plak.host.plist";
const LOG_DIRECTORY: &str = "Library/Logs/Plak";
const SHELL_COMMAND: &str =
    "exec /usr/bin/env -i \"SHELL=${SHELL}\" \"USER=${USER}\" \"LOGNAME=${LOGNAME}\" \"$@\"";

fn xml(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

pub(super) fn render(home: &Path, product_home: &Path, args: &HostInstall) -> CliResult<String> {
    let arguments = service_arguments(home, product_home, args, 103)?;
    if arguments
        .iter()
        .any(|value| value.contains(['\u{fffe}', '\u{ffff}']))
    {
        return Err(CliFailure::new("service paths must be valid XML text"));
    }
    let arguments = ["/bin/sh", "-c", SHELL_COMMAND, "plak-host"]
        .into_iter()
        .chain(arguments.iter().map(String::as_str))
        .map(|value| format!("    <string>{}</string>", xml(value)))
        .collect::<Vec<_>>()
        .join("\n");
    let home = super::path_text(home, "HOME")?;
    let stdout = xml(&format!("{home}/{LOG_DIRECTORY}/host.stdout.log"));
    let stderr = xml(&format!("{home}/{LOG_DIRECTORY}/host.stderr.log"));
    let home = xml(home);
    Ok(format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by plak host install. Do not edit. -->
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>{LABEL}</string>
  <key>ProgramArguments</key>
  <array>
{arguments}
  </array>
  <key>WorkingDirectory</key>
  <string>{home}</string>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <dict>
    <key>SuccessfulExit</key>
    <false/>
  </dict>
  <key>ExitTimeOut</key>
  <integer>90</integer>
  <key>AbandonProcessGroup</key>
  <true/>
  <key>Umask</key>
  <integer>63</integer>
  <key>StandardOutPath</key>
  <string>{stdout}</string>
  <key>StandardErrorPath</key>
  <string>{stderr}</string>
</dict>
</plist>
"#
    ))
}

#[cfg(any(target_os = "macos", test))]
fn next_steps(home: &Path, args: &HostInstall, uid: u32) -> String {
    let path = home.join("Library/LaunchAgents").join(PLIST);
    let path = shell_words::quote(path.to_str().unwrap_or_default());
    let logs = home.join(LOG_DIRECTORY);
    let stdout = logs.join("host.stdout.log");
    let stderr = logs.join("host.stderr.log");
    let stdout = shell_words::quote(stdout.to_str().unwrap_or_default());
    let stderr = shell_words::quote(stderr.to_str().unwrap_or_default());
    let web = shell_words::quote(&args.web);
    format!(
        "launchctl bootstrap gui/{uid} {path}\n\
         # Start it if it is not already running (bootstrap uses RunAtLoad):\n\
         launchctl kickstart gui/{uid}/{LABEL}\n\
         tailscale serve --bg {web}\n\
         tail -F {stdout} {stderr}\n\
         # To stop and remove the LaunchAgent:\n\
         launchctl bootout gui/{uid} {path}\n\
         rm -- {path}\n"
    )
}

#[cfg(target_os = "macos")]
fn prepare_logs(home: &Path) -> CliResult<()> {
    use rustix::fs::{Mode, OFlags};
    use std::os::unix::fs::MetadataExt as _;

    let directory = home.join(LOG_DIRECTORY);
    crate::commands::runner::private_directory(&directory)?;
    for name in ["host.stdout.log", "host.stderr.log"] {
        let path = directory.join(name);
        let file = std::fs::File::from(
            rustix::fs::open(
                &path,
                OFlags::CREATE
                    | OFlags::WRONLY
                    | OFlags::APPEND
                    | OFlags::NOFOLLOW
                    | OFlags::NONBLOCK
                    | OFlags::CLOEXEC,
                Mode::RUSR | Mode::WUSR,
            )
            .map_err(|error| super::failed(error.into()))?,
        );
        let metadata = file.metadata().map_err(super::failed)?;
        if !metadata.is_file()
            || metadata.nlink() != 1
            || metadata.uid() != rustix::process::geteuid().as_raw()
            || metadata.mode() & 0o077 != 0
        {
            return Err(CliFailure::new(format!(
                "{} is not this user's private regular log file",
                path.display()
            )));
        }
    }
    Ok(())
}

#[cfg(target_os = "macos")]
pub(super) fn install(
    home: &Path,
    plist: &str,
    args: &HostInstall,
    output: &mut dyn std::io::Write,
) -> CliResult<super::ProcessOutcome> {
    let path = home.join("Library/LaunchAgents").join(PLIST);
    super::matching_unit(&path, plist).map_err(super::failed)?;
    // Logs must exist before launchd opens its output files, not after host startup.
    prepare_logs(home)?;
    let created = super::install_file(&path, plist).map_err(super::failed)?;
    writeln!(
        output,
        "{} {}",
        if created {
            "Installed"
        } else {
            "Already installed"
        },
        path.display()
    )
    .map_err(super::failed)?;
    output
        .write_all(next_steps(home, args, rustix::process::getuid().as_raw()).as_bytes())
        .map_err(super::failed)?;
    Ok(super::ProcessOutcome::Success)
}

