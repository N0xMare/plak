//! Explicit service-file installation; never enables or starts the host.

use std::io::{self, Write as _};
use std::os::unix::fs::PermissionsExt as _;
use std::path::Path;
#[cfg(not(target_os = "macos"))]
use std::time::{Duration, Instant};

use plakous_hosted::error::{CliFailure, CliResult, ProcessOutcome};

use crate::command::HostInstall;
use crate::home::paths::PlakPaths;

mod launchd;

#[cfg(not(target_os = "macos"))]
const UNIT: &str = "plak-host.service";
const MARKER: &str = "# Generated by plak host install. Do not edit.\n";

pub(crate) fn run(
    args: &HostInstall,
    paths: CliResult<&PlakPaths>,
    output: &mut dyn io::Write,
) -> CliResult<ProcessOutcome> {
    if !matches!(std::env::consts::OS, "linux" | "macos") {
        return Err(CliFailure::new(
            "plak host install is not yet supported on this platform",
        ));
    }
    if !crate::host::AVAILABLE {
        return Err(CliFailure::new(
            "plak host install requires a build with feature web",
        ));
    }
    let home = crate::environment::inherited_home()
        .ok_or_else(|| CliFailure::new("HOME is unavailable or is not UTF-8"))?;
    let home = Path::new(&home);
    let paths = paths?;
    let unit = if std::env::consts::OS == "macos" {
        launchd::render(home, paths.home(), args)?
    } else {
        render(home, paths.home(), args)?
    };
    if std::env::consts::OS == "linux" {
        validate_config_home(home, crate::environment::xdg_config_home().as_deref())?;
    }
    let executable = home.join(".local/bin/plak");
    if !is_executable(&executable) {
        eprintln!(
            "warning: {} is missing or not executable; install plak before starting the service",
            executable.display()
        );
    }
    if args.dry_run {
        output.write_all(unit.as_bytes()).map_err(failed)?;
        return Ok(ProcessOutcome::Success);
    }
    #[cfg(target_os = "macos")]
    {
        launchd::install(home, &unit, args, output)
    }
    #[cfg(not(target_os = "macos"))]
    {
        let path = home.join(".config/systemd/user").join(UNIT);
        let created = install_file(&path, &unit).map_err(failed)?;
        if created {
            reload_manager(home)?;
        }
        writeln!(
            output,
            "{} {}",
            if created {
                "Installed"
            } else {
                "Already installed"
            },
            path.display()
        )
        .map_err(failed)?;
        writeln!(output, "systemctl --user enable --now {UNIT}").map_err(failed)?;
        writeln!(
            output,
            "# To keep the user manager running without a login session:"
        )
        .map_err(failed)?;
        writeln!(output, "loginctl enable-linger \"$USER\"").map_err(failed)?;
        writeln!(
            output,
            "tailscale serve --bg {}",
            shell_words::quote(&args.web)
        )
        .map_err(failed)?;
        writeln!(output, "journalctl --user -u {UNIT} -f").map_err(failed)?;
        Ok(ProcessOutcome::Success)
    }
}

fn failed(error: io::Error) -> CliFailure {
    CliFailure::new(format!("host service installation failed: {error}"))
}

fn path_text<'a>(path: &'a Path, name: &str) -> CliResult<&'a str> {
    let value = path
        .to_str()
        .filter(|value| !value.chars().any(char::is_control));
    if !path.is_absolute() || value.is_none() {
        return Err(CliFailure::new(format!(
            "{name} must be an absolute UTF-8 path without control characters"
        )));
    }
    Ok(value.unwrap_or_default())
}

fn quote(value: &str) -> String {
    format!(
        "\"{}\"",
        value
            .replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('%', "%%")
    )
}

fn service_arguments(
    home: &Path,
    product_home: &Path,
    args: &HostInstall,
    socket_limit: usize,
) -> CliResult<[String; 9]> {
    let home = path_text(home, "HOME")?;
    if home.contains('=') || home.contains(':') {
        return Err(CliFailure::new(
            "HOME must not contain '=' or ':' for host service installation",
        ));
    }
    let product_home = path_text(product_home, "PLAK_HOME")?;
    let socket = args.web.strip_prefix("unix:").ok_or_else(|| {
        CliFailure::new("plak host install requires --web unix:<absolute socket>")
    })?;
    path_text(Path::new(socket), "--web socket")?;
    if socket.len() > socket_limit {
        return Err(CliFailure::new(format!(
            "the --web socket path exceeds the Unix-socket limit of {socket_limit} bytes"
        )));
    }
    let ui = path_text(&args.ui, "--ui")?;
    Ok([
        format!("HOME={home}"),
        format!("PLAK_HOME={product_home}"),
        format!("PATH={home}/.local/bin:/usr/local/bin:/usr/bin:/bin"),
        format!("{home}/.local/bin/plak"),
        "host".into(),
        "--web".into(),
        args.web.clone(),
        "--ui".into(),
        ui.into(),
    ])
}

fn render(home: &Path, product_home: &Path, args: &HostInstall) -> CliResult<String> {
    let args = service_arguments(home, product_home, args, 107)?;
    let environment = args[..3]
        .iter()
        .map(|s| quote(s).replace('$', "$$"))
        .collect::<Vec<_>>()
        .join(" ");
    let command = args[3..]
        .iter()
        .map(|s| quote(s).replace('$', "$$"))
        .collect::<Vec<_>>()
        .join(" ");
    Ok(format!(
        "{MARKER}[Unit]\nDescription=Plak host\n\n[Service]\nExecStart=/usr/bin/env -i {environment} \"SHELL=${{SHELL}}\" \"USER=${{USER}}\" \"LOGNAME=${{LOGNAME}}\" \"XDG_RUNTIME_DIR=%t\" \"DBUS_SESSION_BUS_ADDRESS=unix:path=%t/bus\" \"INVOCATION_ID=${{INVOCATION_ID}}\" {command}\nExecReload=/bin/kill -USR1 $MAINPID\nKillMode=mixed\nKillSignal=SIGTERM\nTimeoutStopSec=90\nRestart=on-failure\nUMask=0077\n# WorkingDirectory is unset: the systemd user default is HOME.\n\n[Install]\nWantedBy=default.target\n"
    ))
}

fn install_file(path: &Path, unit: &str) -> io::Result<bool> {
    if matching_unit(path, unit)? {
        return Ok(false);
    }
    publish_unit(path, unit)?;
    Ok(true)
}

fn matching_unit(path: &Path, unit: &str) -> io::Result<bool> {
    match std::fs::symlink_metadata(path) {
        Ok(metadata) => {
            if metadata.is_file() && metadata.len() == unit.len() as u64 {
                let existing = std::fs::read(path)?;
                // The expected contents include the platform's generated marker.
                if existing == unit.as_bytes() {
                    return Ok(true);
                }
            }
            Err(io::Error::other(format!(
                "refusing to overwrite {}: not the exact generated service file; stop and remove it manually first",
                path.display()
            )))
        }
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(false),
        Err(error) => Err(error),
    }
}

fn publish_unit(path: &Path, unit: &str) -> io::Result<()> {
    let parent = path
        .parent()
        .ok_or_else(|| io::Error::other("unit has no directory"))?;
    std::fs::create_dir_all(parent)?;
    let mut temporary = tempfile::NamedTempFile::new_in(parent)?;
    temporary
        .as_file()
        .set_permissions(std::fs::Permissions::from_mode(0o644))?;
    temporary.write_all(unit.as_bytes())?;
    temporary.as_file().sync_all()?;
    temporary
        .persist_noclobber(path)
        .map_err(|error| error.error)?;
    std::fs::File::open(parent)?.sync_all()?;
    Ok(())
}

fn validate_config_home(home: &Path, configured: Option<&Path>) -> CliResult<()> {
    let expected = home.join(".config");
    if let Some(configured) = configured
        && configured != expected
        && configured
            .canonicalize()
            .ok()
            .zip(expected.canonicalize().ok())
            .is_none_or(|(configured, expected)| configured != expected)
    {
        return Err(CliFailure::new(
            "XDG_CONFIG_HOME must resolve to $HOME/.config so systemd can find plak-host.service",
        ));
    }
    Ok(())
}

fn is_executable(path: &Path) -> bool {
    std::fs::metadata(path)
        .is_ok_and(|metadata| metadata.is_file() && metadata.permissions().mode() & 0o111 != 0)
}

#[cfg(not(target_os = "macos"))]
fn resolve_manager() -> CliResult<std::path::PathBuf> {
    let path = crate::environment::inherited_path().unwrap_or_else(|| "/usr/bin:/bin".into());
    std::env::split_paths(&path).map(|directory| directory.join("systemctl"))
        .find(|path| is_executable(path)).and_then(|path| path.canonicalize().ok())
        .ok_or_else(|| CliFailure::new("unit written, but systemctl was not found on PATH; install it and run systemctl --user daemon-reload"))
}

#[cfg(not(target_os = "macos"))]
fn reload_manager(home: &Path) -> CliResult<()> {
    use std::os::unix::process::CommandExt as _;
    let manager = resolve_manager()?;
    let mut command = std::process::Command::new(manager);
    command
        .args(["--user", "daemon-reload"])
        .env_clear()
        .env("HOME", home)
        .env("PATH", "/usr/bin:/bin")
        .envs(crate::environment::user_manager_environment())
        .stdin(std::process::Stdio::null())
        .process_group(0);
    let mut child = command.spawn().map_err(failed)?;
    let until = Instant::now() + Duration::from_secs(5);
    loop {
        if let Some(status) = child.try_wait().map_err(failed)? {
            return if status.success() {
                Ok(())
            } else {
                Err(CliFailure::new(
                    "unit written, but systemctl --user daemon-reload failed; retry that command before enabling the service",
                ))
            };
        }
        if Instant::now() >= until {
            if let Some(pid) = i32::try_from(child.id())
                .ok()
                .and_then(rustix::process::Pid::from_raw)
            {
                let _ = rustix::process::kill_process_group(pid, rustix::process::Signal::KILL);
            }
            let _ = child.kill();
            let _ = child.wait();
            return Err(CliFailure::new(
                "unit written, but systemctl --user daemon-reload timed out; retry that command before enabling the service",
            ));
        }
        std::thread::sleep(Duration::from_millis(10));
    }
}

