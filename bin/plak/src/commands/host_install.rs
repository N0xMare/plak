//! Explicit service-file installation; never enables or starts the host.

use std::io::{self, Write as _};
use std::os::unix::fs::PermissionsExt as _;
use std::path::Path;
use std::time::{Duration, Instant};

use plakous_hosted::error::{CliFailure, CliResult, ProcessOutcome};

use crate::command::HostInstall;
use crate::home::paths::PlakPaths;

const UNIT: &str = "plak-host.service";
const MARKER: &str = "# Generated by plak host install. Do not edit.\n";

pub(crate) fn run(args: &HostInstall, output: &mut dyn io::Write) -> CliResult<ProcessOutcome> {
    if !cfg!(target_os = "linux") {
        return Err(CliFailure::new(
            "plak host install is not yet supported on this platform",
        ));
    }
    if !cfg!(feature = "web") {
        return Err(CliFailure::new(
            "plak host install requires a build with feature web",
        ));
    }
    let home = crate::environment::inherited_home()
        .ok_or_else(|| CliFailure::new("HOME is unavailable or is not UTF-8"))?;
    let home = Path::new(&home);
    let paths = PlakPaths::from_env_in(None).map_err(CliFailure::new)?;
    let unit = render(home, paths.home(), args)?;
    if args.dry_run {
        output.write_all(unit.as_bytes()).map_err(failed)?;
        return Ok(ProcessOutcome::Success);
    }
    let path = home.join(".config/systemd/user").join(UNIT);
    let created = install_file(&path, &unit).map_err(failed)?;
    if created {
        reload_manager(home)?;
    }
    writeln!(
        output,
        "{} {}",
        if created {
            "Installed"
        } else {
            "Already installed"
        },
        path.display()
    )
    .map_err(failed)?;
    writeln!(output, "systemctl --user enable --now {UNIT}").map_err(failed)?;
    writeln!(
        output,
        "# To keep the user manager running without a login session:"
    )
    .map_err(failed)?;
    writeln!(output, "loginctl enable-linger \"$USER\"").map_err(failed)?;
    writeln!(
        output,
        "tailscale serve --bg {}",
        shell_words::quote(&args.web)
    )
    .map_err(failed)?;
    writeln!(output, "journalctl --user -u {UNIT} -f").map_err(failed)?;
    Ok(ProcessOutcome::Success)
}

fn failed(error: io::Error) -> CliFailure {
    CliFailure::new(format!("host service installation failed: {error}"))
}

fn path_text<'a>(path: &'a Path, name: &str) -> CliResult<&'a str> {
    let value = path
        .to_str()
        .filter(|value| !value.chars().any(char::is_control));
    if !path.is_absolute() || value.is_none() {
        return Err(CliFailure::new(format!(
            "{name} must be an absolute UTF-8 path without control characters"
        )));
    }
    Ok(value.unwrap_or_default())
}

fn quote(value: &str) -> String {
    format!(
        "\"{}\"",
        value
            .replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('%', "%%")
    )
}

fn render(home: &Path, product_home: &Path, args: &HostInstall) -> CliResult<String> {
    let home = path_text(home, "HOME")?;
    let product_home = path_text(product_home, "PLAK_HOME")?;
    let socket = args.web.strip_prefix("unix:").ok_or_else(|| {
        CliFailure::new("plak host install requires --web unix:<absolute socket>")
    })?;
    path_text(Path::new(socket), "--web socket")?;
    if socket.len() >= 108 {
        return Err(CliFailure::new(
            "the --web socket path exceeds the Linux Unix-socket limit of 107 bytes",
        ));
    }
    let ui = path_text(&args.ui, "--ui")?;
    let args = [
        format!("HOME={home}"),
        format!("PLAK_HOME={product_home}"),
        format!("PATH={home}/.local/bin:/usr/local/bin:/usr/bin:/bin"),
        format!("{home}/.local/bin/plak"),
        "host".into(),
        "--web".into(),
        args.web.clone(),
        "--ui".into(),
        ui.into(),
    ];
    let environment = args[..3]
        .iter()
        .map(|s| quote(s).replace('$', "$$"))
        .collect::<Vec<_>>()
        .join(" ");
    let command = args[3..]
        .iter()
        .map(|s| quote(s).replace('$', "$$"))
        .collect::<Vec<_>>()
        .join(" ");
    Ok(format!(
        "{MARKER}[Unit]\nDescription=Plak host\n\n[Service]\nExecStart=/usr/bin/env -i {environment} \"XDG_RUNTIME_DIR=%t\" \"DBUS_SESSION_BUS_ADDRESS=unix:path=%t/bus\" \"INVOCATION_ID=${{INVOCATION_ID}}\" {command}\nExecReload=/bin/kill -USR1 $MAINPID\nKillMode=mixed\nKillSignal=SIGTERM\nTimeoutStopSec=90\nRestart=on-failure\nUMask=0077\nWorkingDirectory={}\n\n[Install]\nWantedBy=default.target\n",
        quote(home)
    ))
}

fn install_file(path: &Path, unit: &str) -> io::Result<bool> {
    match std::fs::symlink_metadata(path) {
        Ok(metadata) => {
            if metadata.is_file()
                && metadata.len() == unit.len() as u64
                && unit.starts_with(MARKER)
                && std::fs::read(path)? == unit.as_bytes()
            {
                return Ok(false);
            }
            return Err(io::Error::other(format!(
                "refusing to overwrite {}: not the exact generated unit; disable and remove it manually first",
                path.display()
            )));
        }
        Err(error) if error.kind() == io::ErrorKind::NotFound => {}
        Err(error) => return Err(error),
    }
    let parent = path
        .parent()
        .ok_or_else(|| io::Error::other("unit has no directory"))?;
    std::fs::create_dir_all(parent)?;
    let mut temporary = tempfile::NamedTempFile::new_in(parent)?;
    temporary
        .as_file()
        .set_permissions(std::fs::Permissions::from_mode(0o644))?;
    temporary.write_all(unit.as_bytes())?;
    temporary.as_file().sync_all()?;
    temporary
        .persist_noclobber(path)
        .map_err(|error| error.error)?;
    std::fs::File::open(parent)?.sync_all()?;
    Ok(true)
}

fn reload_manager(home: &Path) -> CliResult<()> {
    use std::os::unix::process::CommandExt as _;
    let mut command = std::process::Command::new("systemctl");
    command
        .args(["--user", "daemon-reload"])
        .env_clear()
        .env("HOME", home)
        .env("PATH", "/usr/bin:/bin")
        .envs(crate::environment::user_manager_environment())
        .stdin(std::process::Stdio::null())
        .process_group(0);
    let mut child = command.spawn().map_err(failed)?;
    let until = Instant::now() + Duration::from_secs(5);
    loop {
        if let Some(status) = child.try_wait().map_err(failed)? {
            return if status.success() {
                Ok(())
            } else {
                Err(CliFailure::new(
                    "unit written, but systemctl --user daemon-reload failed; retry that command before enabling the service",
                ))
            };
        }
        if Instant::now() >= until {
            if let Some(pid) = i32::try_from(child.id())
                .ok()
                .and_then(rustix::process::Pid::from_raw)
            {
                let _ = rustix::process::kill_process_group(pid, rustix::process::Signal::KILL);
            }
            let _ = child.kill();
            let _ = child.wait();
            return Err(CliFailure::new(
                "unit written, but systemctl --user daemon-reload timed out; retry that command before enabling the service",
            ));
        }
        std::thread::sleep(Duration::from_millis(10));
    }
}

