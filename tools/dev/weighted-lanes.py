#!/usr/bin/env python3
"""Run the serial and durability lanes on several threads, with weights.

A trial layout, not a gate. It writes a copy of `.config/nextest.toml` that adds
`weighted-serial` and `weighted-durability` profiles with the `serial` and
`durability` membership, thread counts above one and per-test weights, and runs
them through nextest's `--config-file`. The copy is generated on every run, so
it always holds the current lanes. The normal lanes and their one-thread
profiles are not changed.

The durability weights scale with `--durability-threads`: half of it for the
three campaigns that run their cuts on their own workers, a quarter (rounded up)
for the ledger-retirement campaigns. The longest tests start first. Each
profile writes `target/nextest/<profile>/junit.xml`, and the run ends with
`tools/perf/nextest_timing.py` over them.

The run shares the build and uses its own scratch directory (the per-checkout
one plus `-w`, or `PLAK_TEST_TMPDIR`), so it does not disturb a gate's files in
the same checkout. Its load does disturb a gate: it runs up to
`--serial-threads`, then `--durability-threads`, tests at once, and on one
machine that makes timing-sensitive tests fail in both. Run it when no gate is
running, or with lower thread counts. It exits non-zero when a lane fails.
"""

from __future__ import annotations

import argparse
import json
import math
import os
from pathlib import Path
import subprocess
import sys
import time
import tomllib

ROOT = Path(__file__).resolve().parents[2]
LANES = ("serial", "durability")
# Campaigns that run their cuts on isolated workers of their own.
HEAVY = (
    "test(=crash_sweep::durability_subset)"
    " | test(=crash_sweep::durability_twin_pilots)"
    " | test(/::image_residency_crash_cuts_recover_without_redispatch$/)"
)
LEDGER = "test(/^crash_sweep::durability_ledger_retirement_/)"
# The four host-restart matrices, the redial test and the busy-root test.
FIRST = (
    "test(/::(tui_host_restart|review_tui_host_restart_switch"
    "|wire_host_restart|wire_host_restart_switch)$/)"
    " | test(=host_skeleton::runner::recovery::a_transient_daemon_failure_keeps_the_redial_bound)"
    " | test(=host_skeleton::runner::recovery::a_busy_roots_child_job_survives_attach_after_host_loss)"
)


def toml_value(value: object) -> str:
    # Multi-line filters stay readable; a JSON string is a valid TOML basic string.
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str) and "\n" in value and "'''" not in value:
        return f"'''\n{value}'''"
    if isinstance(value, (int, str)):
        return json.dumps(value)
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{key} = {toml_value(item)}" for key, item in value.items()) + " }"
    raise SystemExit(f"weighted-lanes: cannot copy a {type(value).__name__} setting")


def profile_text(name: str, base: dict, threads: int, overrides: list[dict]) -> str:
    lines = [f"[profile.{name}]", f"test-threads = {threads}"]
    for key, value in base.items():
        if key not in {"test-threads", "junit", "overrides"}:
            lines.append(f"{key} = {toml_value(value)}")
    for override in overrides + base.get("overrides", []):
        lines += ["", f"[[profile.{name}.overrides]]"]
        lines += [f"{key} = {toml_value(value)}" for key, value in override.items()]
    lines += ["", f"[profile.{name}.junit]", 'path = "junit.xml"', ""]
    return "\n".join(lines)


def weighted_config(serial_threads: int, durability_threads: int) -> str:
    source = (ROOT / ".config/nextest.toml").read_text()
    profiles = tomllib.loads(source)["profile"]
    durability = [
        {"filter": HEAVY, "threads-required": max(1, durability_threads // 2)},
        {"filter": LEDGER, "threads-required": math.ceil(durability_threads / 4)},
        {"filter": FIRST, "priority": 100},
    ]
    return "\n".join(
        [
            source,
            "# Generated by tools/dev/weighted-lanes.py: the trial layout.",
            profile_text("weighted-serial", profiles["serial"], serial_threads, []),
            profile_text(
                "weighted-durability", profiles["durability"], durability_threads, durability
            ),
        ]
    )


def worker_paths(manifest: str) -> dict[str, str]:
    """The one non-test build of each cell worker in the test build."""
    records = [json.loads(line) for line in manifest.splitlines() if line.strip()]
    found = {}
    for variable, binary in [
        ("PLAK_PY_HOST", "plakous-py-host"),
        ("PLAK_JS_HOST", "plakous-js-host"),
    ]:
        paths = {
            row["executable"]
            for row in records
            if row.get("reason") == "compiler-artifact"
            and row.get("target", {}).get("name") == binary
            and "bin" in row.get("target", {}).get("kind", [])
            and row.get("executable")
            and not row.get("profile", {}).get("test")
        }
        if len(paths) != 1:
            raise SystemExit(f"weighted-lanes: expected exactly one built {binary} executable")
        found[variable] = str(Path(paths.pop()).resolve(strict=True))
    return found


def output(command: list[str], env: dict[str, str]) -> str:
    return subprocess.run(
        command, cwd=ROOT, env=env, check=True, stdout=subprocess.PIPE, text=True
    ).stdout


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--serial-threads", type=int, default=4)
    parser.add_argument("--durability-threads", type=int, default=16)
    parser.add_argument("lanes", nargs="*", help="serial, durability or both (the default)")
    args = parser.parse_args(argv)
    args.lanes = args.lanes or list(LANES)
    if set(args.lanes) - set(LANES):
        parser.error(f"lanes are {' and '.join(LANES)}")
    if args.serial_threads < 1 or args.durability_threads < 1:
        parser.error("thread counts must be positive")

    prefix = output(
        ["bash", "-c", 'source tools/gate/dev-tools-prefix.sh; plak_dev_tools_prefix "$PWD"'],
        dict(os.environ),
    ).strip()
    env = dict(os.environ, PATH=f"{prefix}/bin:{os.environ['PATH']}")
    subprocess.run(
        ["bash", "tools/gate/dev-tools.sh", "check-nextest"], cwd=ROOT, env=env, check=True
    )

    if not env.get("PLAK_TEST_TMPDIR"):
        shared = output(["bash", "tools/gate/test-tmpdir.sh"], env).strip()
        scratch = Path(shared + "-w")
        scratch.mkdir(mode=0o700, exist_ok=True)
        env["PLAK_TEST_TMPDIR"] = str(scratch)
    env.update(json.loads(output(["bash", "tools/gate/test-env.sh", "--fresh", "--json"], env)))
    # --json keeps the overrides and provider keys the offline tests must not see.
    for name in output(["bash", "tools/gate/test-env.sh", "--unset-names"], env).split():
        env.pop(name, None)
    plak_home = env.pop("PLAK_HOME")

    target = ["--target", env["CARGO_BUILD_TARGET"]] if env.get("CARGO_BUILD_TARGET") else []
    target_dir = Path(env.get("CARGO_TARGET_DIR") or ROOT / "target")
    if not target_dir.is_absolute():
        target_dir = ROOT / target_dir
    target_dir.mkdir(parents=True, exist_ok=True)
    config = target_dir / "nextest-weighted.toml"
    config.write_text(weighted_config(args.serial_threads, args.durability_threads))
    print(f"weighted-lanes: config {config}", flush=True)

    build = subprocess.run(
        [
            "cargo",
            "test",
            "--no-run",
            "--locked",
            "--workspace",
            "--all-features",
            "--message-format=json",
            *target,
        ],
        cwd=ROOT,
        env=env,
        check=True,
        stdout=subprocess.PIPE,
        text=True,
    )
    lane_env = dict(env, PLAK_HOME=plak_home, **worker_paths(build.stdout))
    nextest = ["cargo", "nextest"]
    common = ["--locked", "--workspace", "--all-features", "--config-file", str(config), *target]

    # A layout filter that matches nothing has lost its test to a rename.
    for name, expression in [
        ("heavy", HEAVY),
        ("ledger", LEDGER),
        ("first", FIRST),
    ]:
        listed = json.loads(
            output(
                [*nextest, "list", *common, "--profile", "weighted-durability", "-E", expression]
                + ["--message-format", "json"],
                lane_env,
            )
        )
        tests = [
            f"{binary} {test}"
            for binary, suite in listed["rust-suites"].items()
            for test, case in suite["testcases"].items()
            if case["filter-match"]["status"] == "matches"
        ]
        print(f"weighted-lanes: {name} weight matches {len(tests)} tests", flush=True)
        for line in tests:
            print(f"  {line}", flush=True)
        if not tests:
            raise SystemExit(f"weighted-lanes: the {name} filter matches no durability test")

    results = []
    for lane in args.lanes:
        profile = f"weighted-{lane}"
        print(f"-- nextest: {profile} --", flush=True)
        started = time.monotonic()
        status = subprocess.run(
            [
                "python3",
                "tools/gate/test-processes.py",
                "--",
                *nextest,
                "run",
                *common,
                "--profile",
                profile,
                # NEXTEST_TEST_THREADS in the caller's environment would override the
                # profile's count, and the weights are fractions of that count.
                "--test-threads",
                str(args.serial_threads if lane == "serial" else args.durability_threads),
            ],
            cwd=ROOT,
            env=lane_env,
        ).returncode
        results.append((profile, round(time.monotonic() - started), status))

    subprocess.run(
        ["python3", "tools/perf/nextest_timing.py", *[profile for profile, _, _ in results]],
        cwd=ROOT,
    )
    for profile, seconds, status in results:
        outcome = "passed" if status == 0 else f"FAILED ({status})"
        print(f"weighted-lanes: {profile} {seconds} s {outcome}")
    return 1 if any(status for _, _, status in results) else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
